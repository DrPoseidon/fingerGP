import simd

enum TrackID: String, CaseIterable, Identifiable {
    case oval, harbor, pass, forest
    var id: String { rawValue }
}

/// Описание трассы: форма осевой линии и параметры.
struct TrackDefinition {
    enum Shape {
        /// Овал-«стадион»: две прямые и две полуокружности.
        case stadium(straight: Float, radius: Float)
        /// Замкнутая линия по опорным точкам со схемы (в пикселях картинки, y вниз).
        /// Сглаживается сплайном и масштабируется так, чтобы длинная сторона была `longSide` метров.
        case spline(points: [SIMD2<Float>], longSide: Float)
    }

    let id: TrackID
    let name: String
    let subtitle: String
    let shape: Shape
    let width: Float
    /// Визуальный масштаб машины (модель в реальных метрах мелковата на экране телефона).
    let carScale: Float

    static func get(_ id: TrackID) -> TrackDefinition {
        switch id {
        case .oval: return oval
        case .harbor: return harbor
        case .pass: return pass
        case .forest: return forest
        }
    }

    static let all: [TrackDefinition] = TrackID.allCases.map(get)

