            [80, 320], [92, 390], [115, 430],
        ], longSide: 1150),
        width: 15, carScale: 2)

    /// «Перевал» — техничная: шпилька после старта, связка «в гору», петля в инфилде и шикана перед финишем.
    static let pass = TrackDefinition(
